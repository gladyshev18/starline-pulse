// Марка топлива в том виде, в котором её можно складывать.
//
// В чеке марка напечатана строкой товара — «АИ-95-К5 Pulsar-95», — и от
// обычного бензина премиальный отличается ровно одним словом в середине.
// Слово это у каждой сети своё, а стоит премиальность три рубля на литр, то
// есть больше, чем цена успевает пройти за месяц. Если оставить обе марки под
// подписью «АИ-95», график покажет не движение цены, а то, какую кнопку нажали
// на колонке.
//
// Поэтому названия сводятся к общему виду: «АИ-95» и «АИ-95 Премиум» — разные
// ряды, а Pulsar Роснефти и ЭКТО Плюс Лукойла — один и тот же ряд, потому что
// сравнивать сети имеет смысл только на одинаковом бензине.

// Варианты, которые предлагают формы заправок и чеков.
export const FUEL_TYPES = ['АИ-92', 'АИ-95', 'АИ-95 Премиум', 'АИ-98', 'АИ-100'] as const

// Фирменные названия премиального бензина. «ЭКТО» само по себе в список не
// входит: у Лукойла так называется и обычный ЭКТО-92, премиальный — только
// «ЭКТО Плюс». Класс по техрегламенту («-К5», «Евро-5») тоже не признак: он
// напечатан и на обычном.
const PREMIUM = /pulsar|пульсар|(?:экто|ecto)[\s-]*(?:плюс|plus)|ultimate|ультимейт|g[\s-]?drive|джи[\s-]?драйв|v[\s-]?power|премиум|premium/i

const OCTANE = /АИ[\s-]*(\d{2,3})/i

export function normaliseFuelType(value: string | null | undefined): string | null {
  if (value == null) return null
  const text = value.replace(/\s+/g, ' ').trim()
  if (!text) return null

  // Руками пишут и без приставки — «95 премиум»; это та же марка, что и
  // «АИ-95 Премиум», и отдельным рядом на графике быть не должна.
  const octane = OCTANE.exec(text)?.[1] ?? /^(\d{2,3})(?!\d)/.exec(text)?.[1]
  // Что не бензин с октановым числом — дизель, газ, незнакомое слово —
  // остаётся как написано: сводить тут нечего, а терять запись жалко.
  if (!octane) return text.slice(0, 50)

  // У сотого премиальность в самом числе: обычного АИ-100 не бывает, и подпись
  // «АИ-100 Премиум» развела бы один и тот же бензин на два ряда.
  const premium = Number(octane) < 100 && PREMIUM.test(text)
  return `АИ-${octane}${premium ? ' Премиум' : ''}`
}
